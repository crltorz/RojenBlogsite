export function getFeaturedPhotos(count = 6): PhotoItem[] {
  const preferred = [
    "p02",
    "p20",
    "p44",
    "p10",
    "p45",
    "p21",
    "p11",
    "p54",
  ];
  const map = new Map(photos.map((photo) => [photo.id, photo]));
  const featured = preferred
    .map((id) => map.get(id))
    .filter((photo): photo is PhotoItem => Boolean(photo));
  return featured.slice(0, count);
}
